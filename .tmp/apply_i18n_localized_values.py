# Use NO pack for nb
packs["nb"] = packs["no"]


def base_lang(filename: str) -> str:
    return filename[:2].lower()


for path in sorted(trans_dir.glob("*.json")):
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    lang = base_lang(path.name)
    pack = packs.get(lang, en_pack)

    # For nb.json fill missing historical keys from no.json if available
    if path.name.lower() == "nb.json":
        no_path = trans_dir / "no.json"
        if no_path.exists():
            no_data = json.loads(no_path.read_text(encoding="utf-8-sig"))
            for k, v in no_data.items():
                data.setdefault(k, v)

    for k, v in en_pack.items():
        # ensure key exists in all files
        data.setdefault(k, v)

    # override with localized values
    for k, v in pack.items():
        data[k] = v

    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

